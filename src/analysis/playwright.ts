// Generates a Playwright test *draft* from recorded steps. The draft is text
// for a developer to review; nothing is executed. Interactions that caused
// mutating requests are emitted commented out, with a warning, so a test never
// creates server data unless the developer opts in.
import type { NetworkEntry, TimelineEvent } from '../shared/types';
import { MUTATING_METHODS, safeUrl } from '../shared/util';

export interface PlaywrightInput {
  /** The request or event the test should reproduce. */
  target?: NetworkEntry;
  timeline: TimelineEvent[];
  entries: NetworkEntry[];
  /** Steps after this time are ignored (usually the anchor time). */
  until: number;
  tabId?: number;
}

const q = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

/** Parses the recorder's click message: Clicked <button#save> "Save order". */
export function locatorForClick(message: string): string | null {
  const m = /^Clicked <([a-z0-9-]+)(?:#([^>]+))?> "(.*)"$/s.exec(message);
  if (!m) return null;
  const [, tag, id, label] = m;
  if (id) return `page.locator(${q(`#${id}`)})`;
  const role = tag === 'a' ? 'link' : tag === 'button' || tag === 'input' ? 'button' : null;
  if (role && label) return `page.getByRole(${q(role)}, { name: ${q(label)} })`;
  if (label) return `page.getByText(${q(label)})`;
  return null;
}

export function buildPlaywrightDraft(input: PlaywrightInput): string {
  const since = input.until - 60_000;
  const inTab = <T extends { tabId: number }>(x: T) => input.tabId === undefined || x.tabId === input.tabId;
  const events = input.timeline
    .filter((t) => inTab(t) && t.timestamp >= since && t.timestamp <= input.until)
    .sort((a, b) => a.timestamp - b.timestamp);
  const firstLoad = [...events].reverse().find((t) => t.kind === 'page-load') ?? events[0];
  // Each mutating request is attributed to the nearest click before it (within 1.5 s).
  const clicks = events.filter((t) => t.kind === 'click');
  const mutationOf = new Map<string, NetworkEntry>();
  for (const e of input.entries) {
    if (!inTab(e) || !MUTATING_METHODS.has(e.method)) continue;
    const click = [...clicks]
      .reverse()
      .find((t) => t.timestamp <= e.startedAt && e.startedAt - t.timestamp <= 1500);
    if (click && !mutationOf.has(click.id)) mutationOf.set(click.id, e);
  }
  const startUrl = firstLoad?.pageUrl || input.target?.pageUrl || '/';
  const lines: string[] = [
    "import { test, expect } from '@playwright/test';",
    '',
    '// Draft generated by Dev Companion from a recorded session. Review before running:',
    '// - Field values were not recorded; fill in test data where marked.',
    '// - Steps that triggered mutating requests (POST/PUT/PATCH/DELETE) are commented out.',
    '//   Enable them only against a test environment.',
    `test(${q(input.target ? `reproduces ${input.target.method} ${safeUrl(input.target.url)?.pathname ?? input.target.url}` : 'reproduces the recorded issue')}, async ({ page }) => {`,
    `  await page.goto(${q(startUrl)});`,
  ];
  for (const t of events) {
    if (t === firstLoad) continue;
    if (t.kind === 'click') {
      const locator = locatorForClick(t.message);
      const mutation = mutationOf.get(t.id);
      const isTarget = mutation && input.target && mutation.id === input.target.id;
      if (!locator) {
        lines.push(`  // Could not derive a locator for: ${t.message}`);
        continue;
      }
      if (mutation) {
        lines.push(
          `  // MUTATION: this click sent ${mutation.method} ${safeUrl(mutation.url)?.pathname ?? mutation.url} (status ${mutation.status ?? mutation.state}).`,
        );
        if (isTarget) {
          lines.push(
            `  // const responsePromise = page.waitForResponse((r) => r.url().includes(${q(safeUrl(mutation.url)?.pathname ?? '')}) && r.request().method() === ${q(mutation.method)});`,
            `  // await ${locator}.click();`,
            '  // const response = await responsePromise;',
            `  // expect(response.status()).toBe(${mutation.status && mutation.status < 400 ? mutation.status : 200}); // recorded: ${mutation.status ?? mutation.state}`,
          );
        } else {
          lines.push(`  // await ${locator}.click();`);
        }
        continue;
      }
      lines.push(`  await ${locator}.click();`);
    } else if (t.kind === 'form-submit') {
      lines.push(`  // TODO: fill the form fields (values are never recorded), then submit: ${t.message}`);
    } else if (t.kind === 'route-change') {
      lines.push(`  await expect(page).toHaveURL(${q(t.detail?.split(' → ')[1] ?? t.pageUrl)});`);
    }
  }
  const target = input.target;
  if (target && !MUTATING_METHODS.has(target.method)) {
    lines.push(
      `  const response = await page.waitForResponse((r) => r.url().includes(${q(safeUrl(target.url)?.pathname ?? target.url)}));`,
      `  expect(response.status()).toBeLessThan(400); // recorded: ${target.status ?? target.state}`,
    );
  }
  lines.push('});', '');
  return lines.join('\n');
}
