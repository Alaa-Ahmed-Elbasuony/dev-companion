// Redacted bug reports (Markdown and JSON) built from an investigation. All
// content comes from stored records, which were redacted before storage; the
// report applies the redaction rules once more as a safety net.
import type { InvestigationResult } from '../analysis/investigation';
import { redactFreeText } from '../analysis/redaction';
import type { EntryBodies, NetworkEntry, RedactionRules, TimelineEvent } from '../shared/types';
import { clip, safeUrl } from '../shared/util';

export interface ReportEnvironment {
  extensionVersion: string;
  userAgent: string;
  origin: string;
  pageUrl?: string;
  /** Framework/build hints from navigation diagnostics (e.g. next.buildId). */
  appVersion?: string;
  serverTracing: string;
  capturedAt: number;
}

export interface BugReportInput {
  investigation: InvestigationResult;
  title: string;
  expected?: string;
  notes?: string;
  environment: ReportEnvironment;
  entries: NetworkEntry[];
  bodies: Map<string, EntryBodies>;
  timeline: TimelineEvent[];
  redaction: RedactionRules;
}

const LEVEL_LABEL = {
  confirmed: 'Confirmed by evidence',
  strong: 'Strongly supported hypothesis',
  possible: 'Possible hypothesis',
  insufficient: 'Insufficient evidence',
} as const;

const RELATION_LABEL = {
  anchor: 'selected',
  explicit: 'linked by shared id',
  'same-trace': 'same server trace',
  'same-connection': 'same connection',
  probable: 'time-based (probable)',
  ambiguous: 'ambiguous',
} as const;

const fence = (text: string, lang = '') => `\`\`\`${lang}\n${text.replace(/```/g, '``​`')}\n\`\`\``;

export function buildBugReportMarkdown(input: BugReportInput): string {
  const { investigation: inv, environment: env } = input;
  const r = (t: string) => redactFreeText(t, input.redaction);
  const lines: string[] = [];
  lines.push(`# ${r(input.title)}`, '');
  lines.push(
    `_Generated by Dev Companion on ${new Date(env.capturedAt).toISOString()}. Values matching the redaction rules were removed before storage._`,
    '',
  );
  lines.push('## Environment', '');
  lines.push(`- Application origin: ${env.origin}`);
  if (env.pageUrl) lines.push(`- Page: ${r(env.pageUrl)}`);
  if (env.appVersion) lines.push(`- Application build: ${env.appVersion}`);
  lines.push(`- Browser: ${env.userAgent}`);
  lines.push(`- Dev Companion: ${env.extensionVersion}`);
  lines.push(`- Server tracing: ${env.serverTracing}`, '');

  lines.push(
    '## Expected behavior',
    '',
    input.expected?.trim() ? r(input.expected.trim()) : '_Not provided._',
    '',
  );
  lines.push('## Actual behavior', '', r(inv.whatHappened), '');
  if (inv.divergence) {
    lines.push(
      '## Earliest verified point of divergence',
      '',
      `${r(inv.divergence.title)} at ${new Date(inv.divergence.time).toLocaleTimeString()}: ${inv.divergence.why} (${LEVEL_LABEL[inv.divergence.level]})`,
      '',
    );
  }

  lines.push('## Steps to reproduce', '', ...inv.reproduction.map(r), '');
  lines.push(
    '> Steps marked MUTATION create or change server data. Reproduce against a test environment.',
    '',
  );

  lines.push('## Relevant events', '', '| Time | Event | Relation |', '| --- | --- | --- |');
  for (const ev of inv.related.slice(0, 40)) {
    lines.push(
      `| ${new Date(ev.time).toLocaleTimeString()} | ${r(ev.title).replace(/\|/g, '\\|')} | ${RELATION_LABEL[ev.relation]}${ev.relation !== 'anchor' ? `: ${r(ev.evidence).replace(/\|/g, '\\|')}` : ''} |`,
    );
  }
  lines.push('');

  const requests = inv.related.filter((ev) => ev.ref.type === 'request').slice(0, 5);
  if (requests.length) {
    lines.push('## Requests', '');
    for (const ev of requests) {
      const e = input.entries.find((x) => x.id === ev.ref.id);
      if (!e) continue;
      const b = input.bodies.get(e.id);
      lines.push(`### ${e.method} ${r(safeUrl(e.url)?.pathname ?? e.url)} → ${e.status ?? e.state}`, '');
      lines.push(`- URL: ${r(e.url)}`, `- Request id: ${e.id}`, `- Duration: ${e.duration ?? '?'} ms`);
      if (e.errorMessage) lines.push(`- Error: ${r(e.errorMessage)}`);
      if (e.requestHeaders.length)
        lines.push(
          '',
          'Request headers:',
          fence(e.requestHeaders.map((h) => `${h.name}: ${r(h.value)}`).join('\n')),
        );
      if (b?.request?.text) lines.push('', 'Request body:', fence(r(clip(b.request.text, 4000)), 'json'));
      if (b?.response?.text)
        lines.push(
          '',
          `Response body${b.response.truncated ? ' (truncated)' : ''}:`,
          fence(r(clip(b.response.text, 4000)), 'json'),
        );
      lines.push('');
    }
  }

  const errors = inv.related.filter((ev) => ev.ref.type === 'timeline' && ev.failed);
  if (errors.length) {
    lines.push('## Console errors', '');
    for (const ev of errors) {
      const t = input.timeline.find((x) => x.id === ev.ref.id);
      lines.push(`- ${r(t?.message ?? ev.title)}`);
      if (t?.stack) lines.push(fence(r(clip(t.stack, 2000))));
    }
    lines.push('');
  }

  lines.push('## Possible causes (ranked)', '');
  if (!inv.causes.length) lines.push('_No rule produced a hypothesis for these events._');
  for (const c of inv.causes.slice(0, 10))
    lines.push(`- **${LEVEL_LABEL[c.level]}:** ${r(c.text)} _(${r(c.because)})_`);
  lines.push('');
  lines.push(
    '## Evidence still missing',
    '',
    ...(inv.missingEvidence.length ? inv.missingEvidence.map((m) => `- ${r(m)}`) : ['_None identified._']),
    '',
  );
  lines.push(
    '## Suggested next steps',
    '',
    ...(inv.nextSteps.length ? inv.nextSteps.map((s) => `- ${r(s)}`) : ['_None._']),
    '',
  );
  lines.push(
    '## Suggested regression tests',
    '',
    ...(inv.regressionTests.length ? inv.regressionTests.map((s) => `- ${r(s)}`) : ['_None._']),
    '',
  );
  if (inv.notificationChecklist) {
    lines.push('## Notification checklist', '', '| Stage | Status | Detail |', '| --- | --- | --- |');
    for (const s of inv.notificationChecklist)
      lines.push(`| ${s.stage} | ${s.status} | ${r(s.detail).replace(/\|/g, '\\|')} |`);
    lines.push('');
  }
  if (input.notes?.trim()) lines.push('## Notes', '', r(input.notes.trim()), '');
  return lines.join('\n');
}

export function buildBugReportJson(input: BugReportInput): string {
  const { investigation: inv } = input;
  const r = (t: string) => redactFreeText(t, input.redaction);
  return JSON.stringify(
    {
      format: 'dev-companion-bug-report',
      version: 1,
      title: r(input.title),
      environment: input.environment,
      expected: input.expected ? r(input.expected) : undefined,
      actual: r(inv.whatHappened),
      divergence: inv.divergence,
      reproduction: inv.reproduction.map(r),
      related: inv.related.map((e) => ({ ...e, title: r(e.title), evidence: r(e.evidence) })),
      causes: inv.causes.map((c) => ({
        level: c.level,
        text: r(c.text),
        because: r(c.because),
        finding: c.findingId,
      })),
      missingEvidence: inv.missingEvidence.map(r),
      nextSteps: inv.nextSteps.map(r),
      regressionTests: inv.regressionTests.map(r),
      notificationChecklist: inv.notificationChecklist,
      notes: input.notes ? r(input.notes) : undefined,
    },
    null,
    2,
  );
}
